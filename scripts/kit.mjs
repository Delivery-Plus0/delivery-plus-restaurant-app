function hashFile(root, file) {
  const path = join(root, file);
  if (!existsSync(path)) return null;
  const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  return createHash('sha256').update(text).digest('hex');
}

function manifestFor(root) {
  return { description: 'Shared UI kit (#155): these files are identical in all three apps. Generated by scripts/kit.mjs.', files: Object.fromEntries(KIT_FILES.map((file) => [file, hashFile(root, file)])) };
}

function readManifest(root) {
  const path = join(root, MANIFEST);
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
}

function writeManifest(root, manifest) {
  writeFileSync(join(root, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
}

/** Differences between two { file: hash } maps, as readable lines. */
function differences(expected, actual, expectedLabel, actualLabel) {
  const files = [...new Set([...Object.keys(expected), ...Object.keys(actual)])].sort();
  return files
    .filter((file) => expected[file] !== actual[file])
    .map((file) =>
      !(file in expected) ? `  ${file}: not in ${expectedLabel}` : !(file in actual) ? `  ${file}: not in ${actualLabel}` : actual[file] === null ? `  ${file}: missing` : `  ${file}: differs`,
    );
}

async function check(remote) {
  const stored = readManifest(ROOT);
  if (!stored) throw new Error(`${MANIFEST} is missing: run "npm run kit:update".`);
  const local = differences(stored.files, manifestFor(ROOT).files, MANIFEST, 'the kit list');
  if (local.length) {
    throw new Error(`Kit files don't match ${MANIFEST}. Change kit files in all three apps together (npm run kit:sync), then npm run kit:update:\n${local.join('\n')}`);
  }
  console.log(`Kit: ${KIT_FILES.length} files match ${MANIFEST}.`);
  if (!remote) return;

  const response = await fetch(REMOTE_MANIFEST);
  if (!response.ok) throw new Error(`Could not read the canonical kit manifest (${response.status}): ${REMOTE_MANIFEST}`);
  const canonical = await response.json();
  const drift = differences(canonical.files, stored.files, 'the canonical manifest', MANIFEST);
  if (drift.length) {
    throw new Error(`This app's kit differs from the canonical manifest (delivery-plus clients/kit-manifest.json). Sync the kit from an up-to-date app:\n${drift.join('\n')}`);
  }
  console.log('Kit: matches the canonical manifest shared by all three apps.');
}

function sync(target) {
  const to = resolve(target);
  if (!existsSync(join(to, 'package.json'))) throw new Error(`${to} is not an app directory`);
  for (const file of KIT_FILES) {
    mkdirSync(dirname(join(to, file)), { recursive: true });
    copyFileSync(join(ROOT, file), join(to, file));
  }
  writeManifest(to, manifestFor(to));
  console.log(`Kit: copied ${KIT_FILES.length} files and ${MANIFEST} to ${to}.`);
}

const [command, arg] = process.argv.slice(2);
try {
  if (command === 'check') await check(arg === '--remote');
  else if (command === 'update') {
    writeManifest(ROOT, manifestFor(ROOT));
    console.log(`Kit: wrote ${MANIFEST} (${KIT_FILES.length} files).`);
  } else if (command === 'sync' && arg) sync(arg);
  else throw new Error('Usage: node scripts/kit.mjs check [--remote] | update | sync <app-dir>');
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
